const dictionaries: Record<Lang, Partial<Record<DictKey, string>>> = { en, ta }

export function translate(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  let s = dictionaries[lang][key] ?? en[key]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  return s
}

/** Hook: `const t = useT(); t('stores')`. Untranslated keys fall back to English. */
export function useT() {
  const lang = useUiStore((s) => s.lang)
  return (key: DictKey, vars?: Record<string, string | number>) => translate(lang, key, vars)
}

export function useLang(): Lang {
  return useUiStore((s) => s.lang)
}

export function pick(l: Localised, lang: Lang): string {
  return l[lang] || l.en
}

